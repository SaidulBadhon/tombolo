# Build the S08/S15 probe app bundles (Command Line Tools only; no Xcode).
#
# usage: build.sh [s08|s15|all]      (default: all)
#
# Output (gitignored) in build/:
#   s08/S08 AdHoc.app          io.github.saidulbadhon.tombolo.spike.s08.adhoc       ad-hoc, hardened runtime
#   s08/S08 SelfSigned.app     io.github.saidulbadhon.tombolo.spike.s08.selfsigned  stable self-signed identity
#   s08/S08 Unsigned.app       io.github.saidulbadhon.tombolo.spike.s08.unsigned    no signature at all
#   s15/selfsigned-1.0.0/S15 Probe.app   io.github.saidulbadhon.tombolo.spike.s15        self-signed 1.0.0
#   s15/selfsigned-1.0.1/S15 Probe.app   io.github.saidulbadhon.tombolo.spike.s15        self-signed 1.0.1
#   s15/adhoc-1.0.0/S15 AdHoc Probe.app  io.github.saidulbadhon.tombolo.spike.s15adhoc   ad-hoc 1.0.0
#   s15/adhoc-1.0.1/S15 AdHoc Probe.app  io.github.saidulbadhon.tombolo.spike.s15adhoc   ad-hoc 1.0.1
#
# Each build compiles the variant name and version into the binary, so every
# bundle's main executable has its own Mach-O UUID (TN3179: Local Network privacy
# misbehaves when executables share a UUID).
#
# Self-signed variants need tools/signing/create-identity.sh to have run once.

set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
out="$here/build"
what="${1:-all}"

exe=TomboloProbe
id_prefix=io.github.saidulbadhon.tombolo.spike

build_app() {
  local app="$1" bundle_id="$2" variant="$3" version="$4" sign="$5"
  local tmp; tmp="$(mktemp -d -t s08build)"
  rm -rf "$app"
  mkdir -p "$app/Contents/MacOS"
  cat >"$tmp/BuildInfo.swift" <<EOF
// Generated by build.sh
enum BuildInfo {
    static let variant = "$variant"
    static let version = "$version"
    static let bundleID = "$bundle_id"
}
EOF
  xcrun swiftc -swift-version 5 -O -target arm64-apple-macos14.0 \
    -o "$app/Contents/MacOS/$exe" "$here/Sources/main.swift" "$tmp/BuildInfo.swift"
  rm -rf "$tmp"

  local name; name="$(basename "$app" .app)"
  cat >"$app/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleIdentifier</key><string>$bundle_id</string>
  <key>CFBundleName</key><string>$name</string>
  <key>CFBundleDisplayName</key><string>$name</string>
  <key>CFBundleExecutable</key><string>$exe</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>CFBundleShortVersionString</key><string>$version</string>
  <key>CFBundleVersion</key><string>$version</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSLocalNetworkUsageDescription</key>
  <string>Tombolo spike S08: finds and connects to test peers on your local network.</string>
  <key>NSBonjourServices</key>
  <array>
    <string>_tombolo._udp</string>
    <string>_tombolo-test._tcp</string>
  </array>
</dict>
</plist>
EOF
  plutil -lint -s "$app/Contents/Info.plist"
  printf 'APPL????' >"$app/Contents/PkgInfo"

  case "$sign" in
    adhoc)
      codesign --force --sign - --options runtime --timestamp=none "$app" ;;
    selfsigned)
      "$repo/tools/signing/sign.sh" "$app" >/dev/null ;;
    unsigned)
      # swiftc's linker adds an ad-hoc "linker-signed" signature; strip it.
      codesign --remove-signature "$app/Contents/MacOS/$exe" ;;
    *) echo "unknown signing mode $sign" >&2; exit 1 ;;
  esac
  printf '%-48s %-11s %s  uuid=%s\n' "${app#"$here"/}" "$sign" "$version" \
    "$(dwarfdump --uuid "$app/Contents/MacOS/$exe" | awk '{print $2}')"
}

# S08_VERSION lets a rebuild act as an "update" of the S08 bundles in place.
v8="${S08_VERSION:-1.0.0}"
if [[ "$what" == s08 || "$what" == all ]]; then
  build_app "$out/s08/S08 AdHoc.app"      "$id_prefix.s08.adhoc"      adhoc      "$v8" adhoc
  build_app "$out/s08/S08 SelfSigned.app" "$id_prefix.s08.selfsigned" selfsigned "$v8" selfsigned
  build_app "$out/s08/S08 Unsigned.app"   "$id_prefix.s08.unsigned"   unsigned   "$v8" unsigned
fi
if [[ "$what" == s15 || "$what" == all ]]; then
  for v in 1.0.0 1.0.1; do
    build_app "$out/s15/selfsigned-$v/S15 Probe.app"     "$id_prefix.s15"      s15-selfsigned "$v" selfsigned
    build_app "$out/s15/adhoc-$v/S15 AdHoc Probe.app"    "$id_prefix.s15adhoc" s15-adhoc      "$v" adhoc
  done
fi
