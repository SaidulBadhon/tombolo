"""Spike S4 — summarise results/s4/raw/*.json into Markdown tables (stdlib only).

Usage: python3 -I scripts/s4-summarize.py [results/s4/raw] > results/s4/summary.md

Every cell is the median over seeds; frame p95 also shows [min–max] over seeds.
Latencies are one-way phone→Mac (video, audio) or Mac→phone→Mac round trips (control),
measured with one system-wide clock; samples from the first 2 s are excluded.
"""
import glob
import json
import os
import statistics
import sys

RAW = sys.argv[1] if len(sys.argv) > 1 else "results/s4/raw"
WIFI = ["clean", "jitter", "loss1", "burst3", "cap100"]
USB = ["usb"]
ORDER = ["quic", "quic+bbr3", "tcp", "tunnel", "tunnel+bbr3", "tunnel-lean+bbr3", "rawtcp"]


def load():
    runs = {}
    for f in sorted(glob.glob(os.path.join(RAW, "*.json"))):
        d = json.load(open(f))
        if not d.get("mac") or not d.get("phone"):
            print(f"<!-- skipped incomplete run {os.path.basename(f)} -->")
            continue
        runs.setdefault((d["cond"], d["transport"]), []).append(d)
    return runs


def cpu_pct(samples, a, b):
    m = {s[0]: s[1] for s in samples}
    if a not in m or b not in m or b <= a:
        return None
    return (m[b] - m[a]) / ((b - a) * 1e6) * 100.0


def windows(d):
    """(media-only CPU window, bulk windows) in whole seconds after t0."""
    bw = d.get("bulk_windows")
    if not bw:  # runs recorded before bulk_windows was added to the result
        bw = [(s, s + 1) for s in (4, 8, 12, 16)] if d["cond"] == "cap100" else [(6, 14)]
    bw = [(int(a), int(b)) for a, b in bw]
    return [2, bw[0][0]], bw


def cpu_split(d, side):
    s = d[side]["cpu_samples"]
    (ma, mb), bulk = windows(d)
    media = cpu_pct(s, ma, mb)
    tot, dur = 0.0, 0
    for a, b in bulk:
        v = cpu_pct(s, a, b)
        if v is None:
            return media, None
        tot += v * (b - a)
        dur += b - a
    return media, tot / dur


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def fmt(x, nd=1):
    return "–" if x is None else f"{x:.{nd}f}"


def g(d, *path):
    for p in path:
        if d is None:
            return None
        d = d.get(p) if isinstance(d, dict) else None
    return d


def row(cond, t, ds):
    f95 = [g(d, "mac", "frame_latency_ms", "all", "p95") for d in ds]
    gen = [d["phone"]["frames_generated"] for d in ds]
    rx = [d["mac"]["frames_received"] for d in ds]
    drop = [100.0 * (a - b) / a for a, b in zip(gen, rx)]
    cp = [cpu_split(d, "phone") for d in ds]
    cm = [cpu_split(d, "mac") for d in ds]
    rng = f"[{fmt(min(f95))}–{fmt(max(f95))}]" if len(ds) > 1 else ""
    return [
        cond,
        f"`{t}`",
        str(len(ds)),
        fmt(med(g(d, "mac", "frame_latency_ms", "all", "p50") for d in ds)),
        f"{fmt(med(f95))} {rng}".strip(),
        fmt(med(g(d, "mac", "frame_latency_ms", "all", "p99") for d in ds)),
        fmt(med(g(d, "mac", "frame_latency_ms", "load", "p95") for d in ds)),
        fmt(med(g(d, "mac", "frame_latency_ms", "noload", "p95") for d in ds)),
        fmt(med(drop)),
        fmt(med(g(d, "mac", "audio", "lost_or_late40_pct") for d in ds), 2),
        fmt(med(g(d, "mac", "audio", "latency_ms", "all", "p95") for d in ds)),
        fmt(med(g(d, "mac", "control_rtt_ms", "all", "p50") for d in ds)),
        fmt(med(g(d, "mac", "control_rtt_ms", "all", "p95") for d in ds)),
        fmt(med(g(d, "mac", "bulk", "mbit_s") for d in ds), 0),
        f"{fmt(med(c[0] for c in cp), 0)} / {fmt(med(c[1] for c in cp), 0)}",
        f"{fmt(med(c[0] for c in cm), 0)} / {fmt(med(c[1] for c in cm), 0)}",
    ]


HEAD = [
    "cond", "transport", "seeds", "frame p50", "frame p95 [range]", "frame p99",
    "frame p95 under bulk", "frame p95 no bulk", "frames lost %", "audio lost+late>40ms %",
    "audio p95", "ctrl RTT p50", "ctrl RTT p95", "bulk Mbit/s",
    "CPU phone % (media / +bulk)", "CPU Mac % (media / +bulk)",
]


def table(runs, conds):
    out = ["| " + " | ".join(HEAD) + " |", "|" + "---|" * len(HEAD)]
    for c in conds:
        for t in ORDER:
            if (c, t) in runs:
                out.append("| " + " | ".join(row(c, t, runs[(c, t)])) + " |")
    return "\n".join(out)


def main():
    runs = load()
    print("# S4 summary (generated by scripts/s4-summarize.py — do not edit)\n")
    print("Units: ms unless stated; CPU is % of one core, process total (user+sys).")
    print("Median over seeds. Loopback + userland impairment: indicative only.\n")
    conds = sorted({c for c, _ in runs}, key=lambda c: (WIFI + USB + [c]).index(c))
    wifi = [c for c in conds if c in WIFI]
    other = [c for c in conds if c not in WIFI]
    if wifi:
        print("## Wi-Fi-like conditions\n")
        print(table(runs, wifi))
    for c in other:
        print(f"\n## {'USB (adb-forward model)' if c == 'usb' else c}\n")
        print(table(runs, [c]))
        delta(runs, c)
    paths(runs)


def delta(runs, cond):
    base = runs.get((cond, "rawtcp"))
    if base:
        b95 = med(g(d, "mac", "frame_latency_ms", "all", "p95") for d in base)
        bl = med(g(d, "mac", "frame_latency_ms", "load", "p95") for d in base)
        print("\n### Added frame latency vs the scrcpy-style baseline (`rawtcp`, plain TCP per channel)\n")
        print("| transport | Δ frame p95 (all) | Δ frame p95 under bulk |")
        print("|---|---|---|")
        for t in ORDER:
            ds = runs.get((cond, t))
            if not ds or t == "rawtcp":
                continue
            a = med(g(d, "mac", "frame_latency_ms", "all", "p95") for d in ds)
            l = med(g(d, "mac", "frame_latency_ms", "load", "p95") for d in ds)
            print(f"| `{t}` | {a - b95:+.1f} | {l - bl:+.1f} |")


def paths(runs):
    print("\n## Path checks (QUIC runs)\n")
    print("Selected path at the end of each QUIC run must be the proxy/relay, never a direct path:\n")
    for (c, t), ds in sorted(runs.items()):
        for d in ds:
            p = g(d, "phone", "transport", "paths")
            if p:
                pr = g(d, "proxy", "down_phone_to_mac") or {}
                print(f"- {c} `{t}` seed {d['seed']}: phone {p}; proxy pkts in/lost/queue-dropped "
                      f"{pr.get('pkts_in')}/{pr.get('lost')}/{pr.get('queue_dropped')}, QUIC lost "
                      f"{g(d, 'phone', 'transport', 'quic_lost_packets')}, "
                      f"clock offset est {g(d, 'mac', 'clock_offset_est_ms')} ms")


if __name__ == "__main__":
    main()
